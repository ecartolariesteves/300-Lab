import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const R = require('../rules.js');
const state = R.newGame(4, () => 0.42);
assert.deepEqual(state.columns.map(c => c.length), [6,6,6,6,5,5,5,5,5,5]);
assert.equal(state.columns.flat().length, 54);
assert.equal(state.stock.length, 50);
assert.equal(R.makeDeck(1,()=>0.3).length,104);
assert.equal(R.makeDeck(2,()=>0.3).length,104);
const mixed = { columns: [[{rank:9,suit:'♠',faceUp:true},{rank:8,suit:'♥',faceUp:true}],[{rank:10,suit:'♣',faceUp:true}],...Array.from({length:8},()=>[])] };
assert.equal(R.canMove(mixed,0,0,1), false);
const same = { columns: [[{rank:9,suit:'♠',faceUp:true},{rank:8,suit:'♠',faceUp:true}],[{rank:10,suit:'♣',faceUp:true}],...Array.from({length:8},()=>[])] };
assert.equal(R.canMove(same,0,0,1), true);
const run = Array.from({length:13},(_,i)=>({rank:13-i,suit:'♠',faceUp:true}));
const complete = {columns:[run,...Array.from({length:9},()=>[])],stock:[],completed:0,moves:0};
assert.equal(R.completeRuns(complete),1); assert.equal(complete.completed,1);

const empty = {columns:[[],...Array.from({length:9},()=>[])],stock:Array.from({length:50},()=>({rank:1,suit:'♠'})),completed:0,moves:0};
assert.equal(R.deal(empty),false);
console.log('✔ Spider: reparto 54/50, secuencias por palo, escalera K→A y bloqueo del mazo');
